#!/usr/bin/env python3
"""M4 tables: x -> (coarse delay, HM) reproducing the original 'SEC / SBC #15 loop / ASL x4 / EOR #$F0 / ADC #$90'."""
def orig(x):
    a = x; c = 1; k = 0
    while True:                       # SBC #$0F with carry; loop while carry set
        r = a - 15 - (1 - c); c = 1 if r >= 0 else 0; a = r & 0xFF; k += 1
        if not c: break
    for _ in range(4):
        c = (a >> 7) & 1; a = (a << 1) & 0xFF
    a ^= 0xF0
    r = a + 0x90 + c; a = r & 0xFF
    return k, a                        # RESP written at cycle 5k+17 (original), HM = a
rows = ['; generated by gen_m4.py: POSC[x] = delay count (k-1) for DEY/BPL, POSHM[x] = HMPx value']
C = []; H = []
for x in range(160):
    k, hm = orig(x); C.append(k - 1); H.append(hm & 0xF0)
def emit(n, v):
    for i in range(0, len(v), 16):
        rows.append('%-8s.byte %s' % (n if i == 0 else '', ','.join('$%02X' % b for b in v[i:i + 16])))
emit('POSC', C); emit('POSHM', H)
rom = open('rom/tp.a26', 'rb').read()
spd = list(rom[0x710:0x740]); off = [v - 0x10 for v in rom[0x70B:0x710]]
emit('SPD', spd); rows.append('SPDOFF  .byte ' + ','.join('$%02X' % v for v in off))
open('src/m4_tables.asm', 'w').write('\n'.join(rows) + '\n')
assert C[0x50] == 5 and H[0x50] == 0x20, (C[0x50], hex(H[0x50]))
print('k range', min(C), max(C), 'HM set', sorted(set(H)))
