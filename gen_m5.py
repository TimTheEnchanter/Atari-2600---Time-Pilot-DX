#!/usr/bin/env python3
"""M5 data.
 src/m5_tables.asm  (bank 3): copies of the bank-0 tables the moved routines use, 56-kill icon tables,
                    boss hit points, icon page data.
 src/m5_boss.inc    (bank 1): boss graphics, two 8-pixel halves per era page at $C6 (left) and $E2 (right).
"""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
rom = open(os.path.join(HERE, 'rom', 'tp.a26'), 'rb').read()
b0, b1 = rom[:4096], rom[4096:]
QUOTA = 56
ICONPG = 0xD5          # bank 3: icon copies live in page $D5 ($D52C-$D59B is free there)
ICBLANK = 0x2C
ICON0 = 0x36           # + 11 * era

out = ['; generated by gen_m5.py']
def row(n, v):
    for i in range(0, len(v), 16):
        out.append('%-8s.byte %s' % (n if i == 0 else '', ','.join('$%02X' % (x & 0xFF) for x in v[i:i + 16])))
row('T_PAGE', b0[0xE3E:0xE43])      # LFE3E enemy page by era
row('T_ECOL', b0[0xD97:0xD9C])      # LFD97 enemy colour
row('T_SCOL', b0[0xD92:0xD97])      # LFD92 ship colour
row('T_FBASE', b0[0xDD8:0xDE0])     # LFDD8 frame base by heading
row('T_SCX', b0[0xFD5:0xFDD])       # LFFD5 scroll x by heading
row('T_SCY', b0[0xFDD:0xFE5])       # LFFDD scroll y
# icon stage by kills left (0..QUOTA): ceil(left * 6 / QUOTA), like LD30D does for 24
row('ICON56', [-(-k * 6 // QUOTA) for k in range(QUOTA + 1)])
# six icon pointer lo tables, indexed by stage + 7 * era: 0 -> blank, $4C/$4D -> this era's copy
orig = [list(b1[0x32B + 7 * i:0x32B + 7 * i + 7]) for i in range(6)]
for p in range(6):
    t = []
    for era in range(5):
        for s in range(7):
            v = orig[p][s]
            t.append(ICBLANK if v == 0 else ICON0 + 11 * era + (v - 0x4C))
    row('ICT%d' % p, t)
row('BOSSHPT', [6, 8, 8, 10, 10])   # hits to bring down each era's boss
open(os.path.join(HERE, 'src', 'm5_tables.asm'), 'w').write('\n'.join(out) + '\n')

# icon page bytes for bank 3 ($D52C..): 10 blank + 11 per era copied from the era page at $4C
pages = list(b0[0xE3E:0xE43])
icon = [0] * 10
for pg in pages:
    o = (pg - 0xD0) * 256
    icon += list(b1[o + 0x4C:o + 0x57])
open(os.path.join(HERE, 'src', 'm5_icons.asm'), 'w').write(
    '; generated by gen_m5.py: bottom-panel icon copies (bank 3, $D52C)\nICONS   .byte ' + ','.join('$%02X' % v for v in icon) + '\n')

# ---- boss graphics: 16 x 10, top row first; '#' = pixel. Facing right (the builder mirrors for left).
