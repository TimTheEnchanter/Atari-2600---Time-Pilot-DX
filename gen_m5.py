ALT = {  # second page of the animated eras
 2: [".....#....#.....",
     "..###......###..",
     ".##############.",
     "################",
     "##.#.#.#.#.#.###",
     "################",
     ".##############.",
     "..#..#....#..#..",
     ".############...",
     "................"],
 4: [".....######.....",
     "...##########...",
     ".##############.",
     "################",
     ".#.#.#.#.#.#.#.#",
     "################",
     ".##############.",
     "...##########...",
     ".....######.....",
     "................"],
}
LB, RB = 0xC6, 0xE2
def halves(rows):
    l = [int(r[:8].replace('.', '0').replace('#', '1'), 2) for r in rows]
    r = [int(r[8:].replace('.', '0').replace('#', '1'), 2) for r in rows]
    return l, r
inc = ['; generated by gen_m5.py: boss halves per era page (left at $xC6, right at $xE2; rows base+3..base+12)']
page_era = {0xD8: 0, 0xD9: 1, 0xDA: 2, 0xDB: 2, 0xDC: 3, 0xDD: 4, 0xDE: 4}
for pg in range(0xD8, 0xDF):
    era = page_era[pg]
    rows = ALT[era] if pg in (0xDB, 0xDE) else BOSS[era]
    l, r = halves(rows)
    data = [0] * (0x100 - LB)
    for i in range(10):              # top row -> highest index (kernel row 12 is drawn first)
        data[LB - LB + 12 - i] = l[i]
        data[RB - LB + 12 - i] = r[i]
    inc.append('BOSS_%02X = $%02X%02X' % (pg, pg, LB))
    inc.append(('    ORG $%04X' % ((pg - 0xD0) * 256 + LB)))
    inc.append(('    RORG $%04X' % (pg * 256 + LB)))
    for i in range(0, len(data), 16):
        inc.append('        .byte ' + ','.join('$%02X' % v for v in data[i:i + 16]))
open(os.path.join(HERE, 'src', 'm5_boss.inc'), 'w').write('\n'.join(inc) + '\n')
import json
bossbytes = {}
for pg in range(0xD8, 0xDF):
    era = page_era[pg]; rows = ALT[era] if pg in (0xDB, 0xDE) else BOSS[era]; l, r = halves(rows)
    data = [0] * (0x100 - LB)
    for i in range(10):
        data[12 - i] = l[i]; data[RB - LB + 12 - i] = r[i]
    bossbytes[pg] = data
os.makedirs(os.path.join(HERE, 'build'), exist_ok=True)
json.dump(bossbytes, open(os.path.join(HERE, 'build', 'boss.json'), 'w'))
