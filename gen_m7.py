#!/usr/bin/env python3
"""M7 presentation data for Time Pilot DX.
 - src/m7_snd.asm : bank 0 sound table SNDT = copy of the original LFF54 table (so all old sound ids stay valid)
                    followed by the new jingles; src/m7_ids.h : their ids (offsets into SNDT), for every bank
 - src/m7_go.asm  : bank 2 'GAME OVER' 48x22 bitmap, 6 column tables (title-kernel format, row 0 = bottom)
 - build/title_patch.json : new rows 12-21 of the title bitmap ('TIME' moved left, 'DX' beside it)
"""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__))
rom = open(os.path.join(HERE, 'rom', 'tp.a26'), 'rb').read()
def b0(a): return rom[a - 0xF000]

# ---------------------------------------------------------------- sounds
old = [b0(a) for a in range(0xFF54, 0xFFC5)]          # 113 bytes, ids $00-$70
# AUDC 4 (pure tone): f = 15700 / Hz - 1
NOTE = {'C5': 29, 'D5': 26, 'E5': 23, 'F5': 22, 'G5': 19, 'A5': 17, 'B5': 15,
        'C6': 14, 'D6': 12, 'E6': 11, 'G6': 9, 'R': 0x80}
def tune(audc, seq):
    out = [audc]
    for n, d in seq:
        out += [NOTE[n] | (0x80 if n == 'R' else 0), d]
    return out + [0]
jingles = [
    ('J_ERA',    tune(0x04, [('C5', 7), ('E5', 7), ('G5', 7), ('C6', 14), ('R', 4), ('G5', 6), ('C6', 24)])),
    ('J_LIFE',   tune(0x04, [('C6', 4), ('E6', 4), ('G6', 4), ('C6', 4), ('E6', 4), ('G6', 14)])),
    ('J_RESCUE', tune(0x04, [('G5', 3), ('C6', 3), ('E6', 8)])),
    ('J_BOSS',   tune(0x0C, [('A5', 6), ('E5', 6), ('A5', 6), ('E5', 6), ('A5', 6), ('E5', 10)])),
]
data = list(old); ids = {}
for name, d in jingles:
    ids[name] = len(data); data += d
assert len(data) <= 256, len(data)
with open(os.path.join(HERE, 'src', 'm7_snd.asm'), 'w') as f:
    f.write('; generated by gen_m7.py: sound table (original LFF54 data, then the M7 jingles). Ids = offsets.\n')
    f.write('SNDT\n')
    for i in range(0, len(data), 16):
        f.write('        .byte ' + ','.join('$%02X' % v for v in data[i:i + 16]) + '\n')
with open(os.path.join(HERE, 'src', 'm7_ids.h'), 'w') as f:
    f.write('; generated by gen_m7.py: jingle ids (offsets into bank 0 SNDT)\n')
    for k, v in ids.items(): f.write('%-8s = $%02X\n' % (k, v))

# ---------------------------------------------------------------- big 7x10 font (2-pixel strokes, title style)
FONT = {
 'G': ['.######', '##....#', '##.....', '##.....', '##..###', '##...##', '##...##', '##...##', '##...##', '.######'],
 'A': ['..###..', '.##.##.', '##...##', '##...##', '##...##', '#######', '##...##', '##...##', '##...##', '##...##'],
 'M': ['##...##', '###.###', '#######', '##.#.##', '##...##', '##...##', '##...##', '##...##', '##...##', '##...##'],
 'E': ['#######', '##.....', '##.....', '##.....', '######.', '##.....', '##.....', '##.....', '##.....', '#######'],
 'O': ['.#####.', '##...##', '##...##', '##...##', '##...##', '##...##', '##...##', '##...##', '##...##', '.#####.'],
 'V': ['##...##', '##...##', '##...##', '##...##', '##...##', '##...##', '.##.##.', '.##.##.', '..###..', '...#...'],
 'R': ['######.', '##...##', '##...##', '##...##', '######.', '##.##..', '##..##.', '##...##', '##...##', '##...##'],
}
def blank(): return [[0] * 48 for _ in range(22)]
def put(bm, word, top, x0, cell=9):          # top = row index of the first (top) font row
    for i, ch in enumerate(word):
        for r, s in enumerate(FONT[ch]):
            for c, p in enumerate(s):
                if p == '#': bm[top - r][x0 + i * cell + c] = 1
go = blank()
put(go, 'GAME', 21, 7)
put(go, 'OVER', 9, 7)
def cols(bm):
    out = []
    for c in range(6):
        out.append([sum(bm[r][c * 8 + k] << (7 - k) for k in range(8)) for r in range(22)])
    return out
with open(os.path.join(HERE, 'src', 'm7_go.asm'), 'w') as f:
    f.write('; generated by gen_m7.py: GAME OVER bitmap for GOKern (6 columns x 22 rows, row 0 = bottom)\n')
    for c, col in enumerate(cols(go)):
        f.write('GO%d     .byte %s\n' % (c, ','.join('$%02X' % v for v in col)))

# ---------------------------------------------------------------- title: rows 12-21 'TIME' + 'DX'
TCOLS = [0xFCA0, 0xFCCE, 0xFE00, 0xFE43, 0xFE71, 0xFE9F]
def trow(r):
    bits = []
    for a in TCOLS:
        v = b0(a + r); bits += [(v >> (7 - k)) & 1 for k in range(8)]
    return bits
DX = ['####.##.##', '##.####.##', '##.##.###.', '##.##..#..', '##.##.###.', '##.####.##', '####.##.##']
DX = [s[:5] + '.' + s[5:] for s in DX]      # D (5) gap X (5): 11 pixels
patch = {}
for r in range(12, 22):
    old = trow(r)
    new = [0] * 48                           # TIME packed left with 1-pixel letter gaps (x 0-33)
    for (a, b), sh in (((5, 12), 5), ((15, 20), 6), ((23, 31), 7), ((34, 41), 8)):
        for x in range(a, b + 1): new[x - sh] = old[x]
    k = 21 - r                               # DX on the top 7 rows (15-21), x 35-45
    if k < len(DX):
        for c, p in enumerate(DX[k]):
            new[35 + c] = 1 if p == '#' else 0
    for ci, a in enumerate(TCOLS):
        patch['%d' % (a + r)] = sum(new[ci * 8 + j] << (7 - j) for j in range(8))
json.dump(patch, open(os.path.join(HERE, 'build', 'title_patch.json'), 'w'))
if __name__ == '__main__':
    for r in range(21, -1, -1): print(''.join('#' if v else '.' for v in go[r]))
    print(ids)
