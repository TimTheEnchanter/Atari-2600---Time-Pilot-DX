#!/usr/bin/env python3
"""Generate M3 data: 16-direction ship frames (bank 1 page $D4) and shot/turn tables (bank 2)."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from shipgen import render
rom = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'rom', 'tp.a26'), 'rb').read()
b1 = rom[4096:]
orig = {0: 0x52C, 2: 0x53C, 4: 0x54C, 6: 0x55C, 8: 0x56C}
frames = []
for f in range(9):
    if f in orig:
        frames.append(list(b1[orig[f]:orig[f] + 16]))           # kernel order: index 15 = top row
    else:
        g = render(f * 22.5)                                   # rows top->bottom
        frames.append([g[15 - i] for i in range(16)])
expl = list(b1[0x57C:0x58C])
out = ['; generated by gen_m3.py - ship frames at $D410 + 16*f, bank 1 page $D4 (index 15 = top row)']
for f, fr in enumerate(frames):
    out.append('SHIP%d   .byte %s   ; heading %.1f deg' % (f, ','.join('$%02X' % v for v in fr), f * 22.5))
out.append('    ORG $04A0')
out.append('    RORG $D4A0')
out.append('SHIPX   .byte %s   ; explosion (A4 = $A0)' % ','.join('$%02X' % v for v in expl))
out.append('SHIPB   .byte %s   ; hidden (A4 = $B0)' % ','.join(['$00'] * 16))
open('src/ship16.asm', 'w').write('\n'.join(out) + '\n')

dx8 = [0, 4, 4, 4, 0, -4, -4, -4]; dy8 = [4, 4, 0, -4, -4, -4, 0, 4]
sx8 = list(rom[0x4A6:0x4AE]); sy8 = list(rom[0x4AE:0x4B6])
def mid(t, d):
    a, b = t[(d // 2) % 8], t[((d + 1) // 2) % 8]
    return (a + b) / 2
DX = [round(mid(dx8, d) / 2) for d in range(16)]
DY = [round(mid(dy8, d) / 2) for d in range(16)]
SX = [round(mid(sx8, d)) for d in range(16)]
SY = [round(mid(sy8, d)) for d in range(16)]
stick = list(rom[0xE2E:0xE3E])
STK = [0xFF if v == 0xFF else v * 2 for v in stick]
LO = [0x10 + 16 * (d if d <= 8 else 16 - d) for d in range(16)]
t = ['; generated by gen_m3.py - 16-direction tables (bank 2)']
def row(n, v): t.append('%-8s.byte %s' % (n, ','.join('$%02X' % (x & 0xFF) for x in v)))
row('SHDX', DX); row('SHDY', DY); row('SHSX', SX); row('SHSY', SY); row('STK16', STK); row('FRLO', LO)
open('src/m3_tables.asm', 'w').write('\n'.join(t) + '\n')
print('DX', DX); print('DY', DY); print('SX', SX); print('SY', SY); print('LO', [hex(x) for x in LO])
